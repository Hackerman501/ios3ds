"""Offline tests of scripts/carryover.py (user data carry-over on update)."""
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

HFS = os.path.join(ROOT, "build", "tools", "hfsplus")
MKFS = shutil.which("mkfs.hfsplus")


def have_tools():
    return os.path.exists(HFS) and MKFS is not None


def make_image(path, size=4 * 1024 * 1024):
    with open(path, "wb") as f:
        f.truncate(size)
    subprocess.run([MKFS, "-v", "T", path], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def hfs(img, *args, check=True):
    return subprocess.run([HFS, img] + list(args), capture_output=True, text=True,
                          check=check)


def set_folder_owner(img, name, uid, gid):
    """Set a folder's owner in a test HFS+ image (no chown in xpwn's CLI).

    HFS+ catalog leaf records are [keyLength, parentID, nameLength, UTF-16BE
    name, record...].  For a folder record the BSD info starts 32 bytes into
    the record: ownerID and groupID, big endian.  Both images are generated by
    the test, so patching the one folder record with this name is enough.
    """
    with open(img, "rb") as f:
        data = bytearray(f.read())
    needle = name.encode("utf-16-be")
    pos, changed = 0, 0
    while True:
        pos = data.find(needle, pos)
        if pos < 0:
            break
        if pos >= 8:
            keylen = struct.unpack_from(">H", data, pos - 8)[0]
            namelen = struct.unpack_from(">H", data, pos - 2)[0]
            record = pos - 8 + 2 + keylen
            if (namelen == len(name) and keylen == 4 + 2 + 2 * namelen and
                    record + 40 <= len(data) and
                    struct.unpack_from(">H", data, record)[0] == 1):
                struct.pack_into(">II", data, record + 32, uid, gid)
                changed += 1
        pos += 1
    if changed != 1:
        raise AssertionError("expected one folder record named %s, found %d" % (name, changed))
    with open(img, "wb") as f:
        f.write(data)


@unittest.skipUnless(have_tools(), "need build/tools/hfsplus and mkfs.hfsplus")
class CarryoverTests(unittest.TestCase):
    def setUp(self):
        self.td = tempfile.mkdtemp()
        self.old = os.path.join(self.td, "old.hfs")
        self.new = os.path.join(self.td, "new.hfs")
        for p in (self.old, self.new):
            make_image(p)
        import carryover
        self.carryover = carryover
        self.hfs = HFS
        dirs = ("/private", "/private/var", "/private/var/mobile",
                "/private/var/mobile/Library",
                "/private/var/mobile/Library/Preferences",
                "/private/var/mobile/Library/Caches",
                "/private/var/mobile/Library/Logs",
                "/private/var/mobile/Media",
                "/private/var/mobile/Media/iTunes_Control",
                "/private/var/mobile/Media/DCIM",
                "/private/var/Keychains",
                "/private/var/preferences",
                "/private/var/preferences/SystemConfiguration")
        for img in (self.old, self.new):
            for d in dirs:
                hfs(img, "mkdir", d, check=False)
            # mobile is 501:501 in a real iOS disk; Keychains/SystemConfiguration
            # stay root, so one test image covers both owners
            for name in ("mobile", "Library", "Preferences", "Caches", "Logs",
                         "Media", "DCIM", "iTunes_Control"):
                set_folder_owner(img, name, 501, 501)

    def tearDown(self):
        shutil.rmtree(self.td, ignore_errors=True)

    def add(self, img, path, text, mode="0644"):
        tmp = os.path.join(self.td, "payload")
        with open(tmp, "w") as f:
            f.write(text)
        hfs(img, "add", tmp, path)
        hfs(img, "chmod", mode, path)

    def _ls_entry(self, img, path):
        r = hfs(img, "ls", os.path.dirname(path), check=False)
        for line in r.stdout.splitlines():
            parts = line.split()
            if len(parts) >= 7 and parts[-1] == os.path.basename(path):
                return parts  # mode uid gid size ...
        return None

    def _ls_mode(self, img, path):
        e = self._ls_entry(img, path)
        return e[0] if e else None

    def test_files_survive_with_mode_and_owner(self):
        self.add(self.old, "/private/var/mobile/Library/Preferences/pref.plist", "hello")
        self.add(self.old, "/private/var/Keychains/kc.key", "secret", "0600")
        status = self.carryover.carry_over(self.old, self.new, self.hfs,
                                           backup=False, verbose=False)
        self.assertEqual(status, "carried")
        self.assertEqual(status.reason, "")
        self.assertIsNone(status.backup)
        # mode, uid, gid and content of the mobile-owned plist
        e = self._ls_entry(self.new, "/private/var/mobile/Library/Preferences/pref.plist")
        self.assertEqual(e[:4], ["100644", "501", "501", "5"])
        r = subprocess.run([self.hfs, self.new, "cat",
                            "/private/var/mobile/Library/Preferences/pref.plist"],
                           capture_output=True)
        self.assertEqual(r.stdout, b"hello")
        # the keychain file stays root-owned with its 0600 mode
        e = self._ls_entry(self.new, "/private/var/Keychains/kc.key")
        self.assertEqual(e[:4], ["100600", "0", "0", "6"])
        # directories keep their owners too
        e = self._ls_entry(self.new, "/private/var/mobile/Library")
        self.assertEqual(e[1:3], ["501", "501"])

    def test_exclusions_and_new_music_library_win(self):
        excluded = (
            ("/private/var/mobile/Library/Caches/com.apple.mobileinstallation.plist", "cache"),
            ("/private/var/mobile/Library/Logs/sys.log", "log"),
            ("/private/var/mobile/Media/DCIM/IMG_0001.sqlite-journal", "journal"),
            ("/private/var/mobile/Media/DCIM/IMG_0002.lock", "lock"),
            ("/private/var/mobile/Media/iTunes_Control/old.itdb", "old library"),
        )
        for path, text in excluded:
            self.add(self.old, path, text)
        # the freshly built image's Music library must survive the carry-over
        self.add(self.new, "/private/var/mobile/Media/iTunes_Control/new.itdb", "new library")
        self.add(self.old, "/private/var/mobile/Media/DCIM/IMG_0003.JPG", "photo")
        status = self.carryover.carry_over(self.old, self.new, self.hfs,
                                           backup=False, verbose=False)
        self.assertEqual(status, "carried")
        for path, _ in excluded:
            self.assertIsNone(self._ls_mode(self.new, path), path)
        self.assertEqual(subprocess.run([self.hfs, self.new, "cat",
                                         "/private/var/mobile/Media/iTunes_Control/new.itdb"],
                                        capture_output=True).stdout, b"new library")
        self.assertIsNotNone(self._ls_mode(self.new, "/private/var/mobile/Media/DCIM/IMG_0003.JPG"))

    def test_data_that_does_not_fit_keeps_backup(self):
        self.add(self.old, "/private/var/mobile/Media/DCIM/pic", "photo")
        self.assertGreater(self.carryover.free_space(self.hfs, self.new), 0)
        # pretend the new disk has no room: the old disk must survive intact
        from unittest.mock import patch
        with patch.object(self.carryover, "free_space", return_value=1):
            status = self.carryover.carry_over(self.old, self.new, self.hfs,
                                               backup=False, verbose=False)
        self.assertEqual(status, "nothing")
        self.assertEqual(status.reason, "does not fit")
        self.assertTrue(os.path.isfile(self.old + ".bak"))
        self.assertEqual(os.path.getsize(self.old + ".bak"), os.path.getsize(self.old))
        self.assertIsNone(self._ls_mode(self.new, "/private/var/mobile/Media/DCIM/big"))

    def test_failed_file_keeps_backup(self):
        self.add(self.old, "/private/var/mobile/Library/Preferences/pref.plist", "hello")
        wrapper = os.path.join(self.td, "hfsplus-fail")
        with open(wrapper, "w") as f:
            f.write('#!/bin/sh\n'
                    'if [ "$2" = extract ] && [ "$3" = '
                    '"/private/var/mobile/Library/Preferences/pref.plist" ]; then\n'
                    '  echo simulated extract failure >&2\n  exit 1\nfi\n'
                    'exec "%s" "$@"\n' % self.hfs)
        os.chmod(wrapper, 0o755)
        status = self.carryover.carry_over(self.old, self.new, wrapper,
                                           backup=False, verbose=False)
        self.assertEqual(status, "partial")
        self.assertTrue(os.path.isfile(self.old + ".bak"))
        self.assertEqual(os.path.getsize(self.old + ".bak"), os.path.getsize(self.old))

    def test_missing_old_warns_and_continues(self):
        bogus = os.path.join(self.td, "nope.hfs")
        status = self.carryover.carry_over(bogus, self.new, self.hfs,
                                           backup=False, verbose=False)
        self.assertEqual(status, "nothing")
        self.assertIsNone(status.backup)

    def test_fresh_env_skips(self):
        self.add(self.old, "/private/var/mobile/Library/Preferences/pref.plist", "hello")
        os.environ["IOS3DS_FRESH"] = "1"
        try:
            status = self.carryover.carry_over(self.old, self.new, self.hfs,
                                               backup=False, verbose=False)
            self.assertEqual(status, "nothing")
            self.assertIsNone(self._ls_mode(self.new, "/private/var/mobile/Library/Preferences/pref.plist"))
        finally:
            os.environ.pop("IOS3DS_FRESH", None)


class MksdCarryOptInTests(unittest.TestCase):
    """make sd must not carry from the last build unless asked to."""

    def test_parser_has_no_default_carry_from(self):
        import mksd
        self.assertIsNone(mksd.parser().parse_args([]).carry_from)
        self.assertEqual(mksd.parser().parse_args(["--carry-from", "/tmp/old.hfs"]).carry_from,
                         "/tmp/old.hfs")


if __name__ == "__main__":
    unittest.main()
