stage_test() {
    say "test: hello (MH_EXECUTE) + testbundle (MH_BUNDLE)"
    local t="$TC/test" cc="$ROOT/scripts/ios-cc" od
    od="$(command -v llvm-objdump-18 || command -v llvm-objdump)"
    mkdir -p "$t"
    cat > "$t/hello.c" <<'EOF'
#include <unistd.h>
#include <stdlib.h>
static const char msg[] = "hello from ios3ds\n";
/* 64-bit division by a variable: pulls ___udivdi3 from the static builtins. */
unsigned long long scale(unsigned long long a, unsigned b) { return a / b; }
int main(int argc, char **argv)
{
    (void)argv;
    write(2, msg, sizeof msg - 1);
    exit((int)scale(0, (unsigned)argc));
}
EOF
    cat > "$t/testbundle.c" <<'EOF'
#include <string.h>
__attribute__((visibility("default")))
int ios3ds_bundle_answer(const char *s) { return 42 + (int)strlen(s); }
EOF
    "$cc" -O2 -Wall "$t/hello.c" -o "$t/hello"
    "$cc" -O2 -Wall -bundle "$t/testbundle.c" -o "$t/testbundle.bundle"
    "$cc" -O2 -Wall -dynamiclib -install_name /usr/lib/libios3dstest.dylib \
        "$t/testbundle.c" -o "$t/libios3dstest.dylib"
    local f
    for f in hello testbundle.bundle libios3dstest.dylib; do
        echo "--- $f"
        "$od" --macho --private-headers "$t/$f" > "$t/$f.txt"
        sed -n '3,4p' "$t/$f.txt"
        grep -E '^ +cmd LC_(UNIXTHREAD|MAIN|CODE_SIGNATURE|LOAD_DYLIB|ID_DYLIB|LOAD_DYLINKER|VERSION_MIN_IPHONEOS|DYLD_INFO_ONLY)|^ +name |^ +version ' "$t/$f.txt" | sed 's/^ */    /'
        grep -q 'ARM .*V6' "$t/$f.txt" || die "$f: not ARM/V6"
        grep -q 'name /usr/lib/libSystem.B.dylib' "$t/$f.txt" || die "$f: no libSystem load command"
        grep -q 'LC_CODE_SIGNATURE' "$t/$f.txt" || die "$f: not signed"
    done
    grep -q LC_UNIXTHREAD "$t/hello.txt" || die "hello: no LC_UNIXTHREAD"
    "$TC/bin/$TOOLPFX-nm" -u "$t/hello" | tr '\n' ' '; echo
    echo "OK"
}

