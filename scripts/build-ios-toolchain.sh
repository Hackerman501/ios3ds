#!/usr/bin/env bash
# Build the ARMv6 / iOS 4.2.1 Mach-O userland toolchain from scratch (Linux,
# no root). Everything lands in build/toolchain/ (gitignored):
#
#   bin/arm-apple-darwin10-ld ...  cctools + ld64 (tpoechtrager/cctools-port)
#   bin/ldid                       ad-hoc code signer (ProcursusTeam/ldid)
#   bin/ios-mkstub                 stub-dylib generator (reads the dyld cache)
#   lib/libclang_rt.builtins-armv6.a   compiler-rt builtins (static, hidden)
#   sdk/                           stub SDK: hand-written headers, crt1, and
#                                  stub dylibs whose export lists are read
#                                  from the user's own dyld_shared_cache, or,
#                                  without an IPSW (CI), from the committed
#                                  scripts/ios-sdk-symbols.json (only the
#                                  symbols our own tools import)
#
# Needs: clang (>= 10, with the ARM backend), cmake, ninja, make, git, curl,
# python3, libssl-dev, uuid-dev. For full stub dylibs it also needs
# build/staging/rootfs.hfs + build/tools/hfsplus (from `make fwprep`).
# No Apple SDK is downloaded.
#
#   scripts/build-ios-toolchain.sh            # everything (skips finished stages)
#   scripts/build-ios-toolchain.sh sdk test   # only these stages
#   scripts/build-ios-toolchain.sh --clean    # wipe build/toolchain first
#
# Stages: dispatch cctools ldid sdk builtins test  (default)
#         symbols   regenerate scripts/ios-sdk-symbols.json (needs the IPSW's
#                   dyld cache): the SDK source used where there is no IPSW (CI)
# Use it through scripts/ios-cc.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TC="$ROOT/build/toolchain"
SRC="$TC/src"
SDK="$TC/sdk"
JOBS="$(nproc 2>/dev/null || echo 4)"
CC_HOST="${CC_HOST:-clang}"
CXX_HOST="${CXX_HOST:-clang++}"
TRIPLE=armv6-apple-ios4.2
TOOLPFX=arm-apple-darwin10
SYMLIST="$ROOT/scripts/ios-sdk-symbols.json"

# Pinned sources.
DISPATCH_URL=https://github.com/tpoechtrager/apple-libdispatch.git
DISPATCH_REV=75d416fbffb9ef05e94559d193917ffb007c6f0d
CCTOOLS_URL=https://github.com/tpoechtrager/cctools-port.git
CCTOOLS_REV=ef969083aecf77dee1814d6961a06b88af23edef      # cctools 1035.1.102, ld64 957.1
LDID_URL=https://github.com/ProcursusTeam/ldid.git
LDID_REV=af86971ae72ec3ed3d0a699107c4e882324c941b         # 2.1.5-procursus7
LIBPLIST_URL=https://github.com/libimobiledevice/libplist/releases/download/2.6.0/libplist-2.6.0.tar.bz2
LIBPLIST_SHA=67be9ee3169366589c92dc7c22809b90f51911dd9de22520c39c9a64fb047c9c
CRT_VER=18.1.3
CRT_URL=https://github.com/llvm/llvm-project/releases/download/llvmorg-$CRT_VER/compiler-rt-$CRT_VER.src.tar.xz
CRT_SHA=9a7df9300413696b0c4f7ff1e2729cb82aca375f35c05d698c44f26a4edf1c27

# Stub dylibs generated by default (install names inside the dyld cache).
# More can be added any time:  build/toolchain/bin/ios-mkstub <install-name>...
