say() { printf '\033[1m== %s\033[0m\n' "$*"; }
die() { echo "error: $*" >&2; exit 1; }

fetch_git() {   # url rev dir
    if [[ ! -d "$3/.git" ]]; then
        mkdir -p "$3"
        git -C "$3" init -q
        git -C "$3" remote add origin "$1"
    fi
    if [[ "$(git -C "$3" rev-parse HEAD 2>/dev/null)" != "$2" ]]; then
        git -C "$3" fetch -q --depth 1 origin "$2"
        git -C "$3" checkout -q FETCH_HEAD
    fi
}

fetch_tar() {   # url sha256 file dir
    if [[ ! -s "$3" ]]; then curl -fsSL -o "$3" "$1"; fi
    echo "$2  $3" | sha256sum -c --quiet - || die "checksum mismatch: $3"
    if [[ ! -d "$4" ]]; then
        mkdir -p "$4"
        tar xf "$3" -C "$4" --strip-components=1
    fi
}

# --------------------------------------------------------------------------
stage_dispatch() {   # libdispatch + BlocksRuntime: host deps of cctools-port
    [[ -e "$TC/lib/libdispatch.so" && -e "$TC/lib/libBlocksRuntime.so" ]] && return
    say "libdispatch"
    fetch_git "$DISPATCH_URL" "$DISPATCH_REV" "$SRC/apple-libdispatch"
    cmake -S "$SRC/apple-libdispatch" -B "$TC/dispatch-build" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DBUILD_TESTING=OFF \
        -DCMAKE_C_COMPILER="$CC_HOST" -DCMAKE_CXX_COMPILER="$CXX_HOST" \
        -DCMAKE_INSTALL_PREFIX="$TC" > "$TC/dispatch-build.log" 2>&1
    ninja -C "$TC/dispatch-build" install >> "$TC/dispatch-build.log" 2>&1
}

stage_cctools() {    # ld64 + cctools, no libtapi (we link against real stub dylibs)
    [[ -x "$TC/bin/$TOOLPFX-ld" ]] && return
    say "cctools-port (ld64)"
    fetch_git "$CCTOOLS_URL" "$CCTOOLS_REV" "$SRC/cctools-port"
    mkdir -p "$TC/cctools-build"
    (
        cd "$TC/cctools-build"
        CC="$CC_HOST" CXX="$CXX_HOST" CPPFLAGS="-I$TC/include" \
        LDFLAGS="-L$TC/lib -Wl,-rpath,$TC/lib" \
            "$SRC/cctools-port/cctools/configure" --prefix="$TC" \
            --target="$TOOLPFX" --disable-tapi-support --disable-lto-support
        make -j"$JOBS"
        make install
    ) > "$TC/cctools-build.log" 2>&1 || die "cctools build failed, see $TC/cctools-build.log"
}

stage_ldid() {
    [[ -x "$TC/bin/ldid" ]] && return
    say "ldid"
    fetch_tar "$LIBPLIST_URL" "$LIBPLIST_SHA" "$SRC/libplist.tar.bz2" "$SRC/libplist"
    mkdir -p "$TC/plist-build"
    (
        cd "$TC/plist-build"
        "$SRC/libplist/configure" --prefix="$TC" --without-cython \
            --disable-shared --enable-static --with-pic
        make -j"$JOBS"
        make install
    ) > "$TC/plist-build.log" 2>&1 || die "libplist build failed, see $TC/plist-build.log"
    fetch_git "$LDID_URL" "$LDID_REV" "$SRC/ldid"
    # ldid 2.1.5 does not build against OpenSSL 4 headers (issue #7): use an
    # installed OpenSSL 3 header set then (CPATH, so ldid's own CXXFLAGS stay)
    local ssl_inc="" ssl_major
    ssl_major=$(sed -n 's/^# *define OPENSSL_VERSION_MAJOR *\([0-9]*\).*/\1/p' /usr/include/openssl/opensslv.h 2>/dev/null | head -1)
    if [[ -n "$ssl_major" && "$ssl_major" -ge 4 ]]; then
        for d in /usr/include/openssl-3 /usr/include/openssl3 /usr/local/opt/openssl@3/include /opt/homebrew/opt/openssl@3/include; do
            [[ -f "$d/openssl/opensslv.h" ]] && { ssl_inc=$d; break; }
        done
        [[ -n "$ssl_inc" ]] || die "ldid needs OpenSSL 3 headers, the system has OpenSSL $ssl_major: install OpenSSL 3 (e.g. the openssl-3 / libssl3-dev package) and run this again"
        say "ldid: OpenSSL $ssl_major system headers, building against $ssl_inc"
    fi
    local envpre=()
    [[ -n "$ssl_inc" ]] && envpre=(env "CPATH=${ssl_inc}${CPATH:+:$CPATH}")
    "${envpre[@]}" make -C "$SRC/ldid" -j"$JOBS" CXX="$CXX_HOST" VERSION=2.1.5-procursus7 \
        LIBPLIST_INCLUDES="-I$TC/include" LIBPLIST_LIBS="$TC/lib/libplist-2.0.a" \
        > "$TC/ldid-build.log" 2>&1 || die "ldid build failed, see $TC/ldid-build.log"
    install -m 755 "$SRC/ldid/ldid" "$TC/bin/ldid"
}

