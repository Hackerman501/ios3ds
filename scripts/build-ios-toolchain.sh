Reads a dylib image out of the iOS 4 dyld shared cache (dyld_v1 format),
takes its install name, versions, re-exports and exported symbol *names*,
and links an empty armv6 dylib exporting the same names into
<sdk>/<install-name>. No Apple code is copied.

Without a dyld cache (e.g. on CI), --symbols reads the same facts from a
JSON list instead. scripts/ios-sdk-symbols.json is such a list, restricted to
the symbols our own tools import (--write-list makes it from the cache).

  ios-mkstub [--cache F] [--sdk D] --list
  ios-mkstub [--cache F] [--sdk D] <install-name>...
  ios-mkstub --symbols LIST.json [--sdk D] <install-name>...
  ios-mkstub [--cache F] --write-list LIST.json --used BIN... -- <install-name>...
"""
import argparse, json, os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.realpath(__file__))
TC = os.path.dirname(HERE)

LC_SEGMENT, LC_SYMTAB, LC_DYSYMTAB = 0x1, 0x2, 0xB
LC_ID_DYLIB, LC_REEXPORT_DYLIB = 0xD, 0x8000001F
N_EXT, N_PEXT, N_TYPE, N_STAB = 0x01, 0x10, 0x0E, 0xE0
N_ABS, N_SECT, N_INDR = 0x2, 0xE, 0xA
N_WEAK_DEF = 0x0080


class Cache:
    def __init__(self, path):
        self.d = open(path, 'rb').read()
        if not self.d.startswith(b'dyld_v1 '):
            sys.exit('%s: not a dyld_v1 shared cache' % path)
        mo, mc, io, ic = struct.unpack_from('<4I', self.d, 16)
        self.maps = [struct.unpack_from('<3Q', self.d, mo + 32 * i) for i in range(mc)]
        self.images = {}
        for i in range(ic):
            addr, _, _, po, _ = struct.unpack_from('<3Q2I', self.d, io + 32 * i)
            self.images[self.cstr(po)] = addr

    def cstr(self, off):
        return self.d[off:self.d.index(b'\0', off)].decode('latin-1')

    def off(self, addr):
        for a, s, o in self.maps:
            if a <= addr < a + s:
                return addr - a + o
        raise ValueError('unmapped address %#x' % addr)

    def image(self, name):
        d, base = self.d, self.off(self.images[name])
        ncmds = struct.unpack_from('<I', d, base + 16)[0]
        p = base + 28
        info = dict(name=name, cur=0x10000, compat=0x10000, reexports=[], syms=[])
        sects, symtab = [], None
        for _ in range(ncmds):
            cmd, size = struct.unpack_from('<2I', d, p)
            if cmd == LC_SEGMENT:
                seg = d[p + 8:p + 24].rstrip(b'\0').decode()
                nsects = struct.unpack_from('<I', d, p + 48)[0]
                sects += [seg] * nsects
            elif cmd == LC_SYMTAB:
                symtab = struct.unpack_from('<4I', d, p + 8)
            elif cmd == LC_ID_DYLIB:
                o, _, info['cur'], info['compat'] = struct.unpack_from('<4I', d, p + 8)
                info['name'] = self.cstr(p + o)
            elif cmd == LC_REEXPORT_DYLIB:
                info['reexports'].append(self.cstr(p + struct.unpack_from('<I', d, p + 8)[0]))
            p += size
        symoff, nsyms, stroff, _ = symtab
        seen = set()
        for i in range(nsyms):
            strx, typ, sect, desc, _ = struct.unpack_from('<IBBHI', d, symoff + 12 * i)
            if typ & N_STAB or not typ & N_EXT or typ & N_PEXT:
                continue
            kind = typ & N_TYPE
            if kind not in (N_ABS, N_SECT, N_INDR):
                continue
            sym = self.cstr(stroff + strx)
            if not sym or sym in seen or '"' in sym or '\n' in sym:
                continue
            seen.add(sym)
            text = kind != N_SECT or not (0 < sect <= len(sects)) or sects[sect - 1] == '__TEXT'
            info['syms'].append((sym, text, bool(desc & N_WEAK_DEF)))
        return info


def ver(v):
    return '%d.%d.%d' % (v >> 16, (v >> 8) & 0xFF, v & 0xFF)


def unver(s):
    a, b, c = (list(map(int, s.split('.'))) + [0, 0])[:3]
    return a << 16 | b << 8 | c


class SymbolList:
    """The Cache interface, backed by a JSON symbol list (--symbols)."""
    def __init__(self, path):
        self.d = json.load(open(path))['dylibs']
        self.images = {n: 0 for n in self.d}

    def image(self, name):
        e = self.d[name]
        weak = set(e.get('weak', []))
        syms = [(s, True, s in weak) for s in e.get('text', [])]
        syms += [(s, False, s in weak) for s in e.get('data', [])]
        return dict(name=name, cur=unver(e['current']), compat=unver(e['compat']),
                    reexports=list(e.get('reexports', [])), syms=syms)


def write_list(cache, path, used_bins, names):
    """Symbol list for `names`, keeping only the symbols `used_bins` import."""
    nm = os.path.join(TC, 'bin', 'arm-apple-darwin10-nm')
    used = set()
    for b in used_bins:
        out = subprocess.check_output([nm, '-u', '-j', b], text=True)
        used.update(l.strip() for l in out.splitlines() if l.strip())
    dylibs, seen, todo = {}, set(), list(names)
    while todo:
        n = todo.pop(0)
        if n in seen:
            continue
        seen.add(n)
        info = cache.image(n)
        keep = [s for s in info['syms'] if s[0] in used]
        dylibs[info['name']] = {
            'current': ver(info['cur']), 'compat': ver(info['compat']),
            'reexports': info['reexports'],
            'text': sorted(s for s, t, _ in keep if t),
            'data': sorted(s for s, t, _ in keep if not t),
            'weak': sorted(s for s, _, w in keep if w)}
        todo += [r for r in info['reexports'] if r in cache.images]
    found = {s for e in dylibs.values() for k in ('text', 'data') for s in e[k]}
    missing = sorted(used - found)
    with open(path, 'w') as f:
        json.dump({'_comment': 'Link-time symbol list for the ios3ds stub SDK (scripts/build-ios-toolchain.sh, '
                               'ios-mkstub --symbols): dylib install names and versions, and the names of only '
                               'those symbols our own tools import. Regenerate: scripts/build-ios-toolchain.sh symbols',
                   'dylibs': dylibs}, f, indent=1, sort_keys=True)
        f.write('\n')
    print('wrote %s: %d dylibs, %d imported symbols%s' % (
        path, len(dylibs), len(found),
        '' if not missing else '; not in these dylibs: ' + ' '.join(missing)))


def mkstub(cache, sdk, name, done):
    if name in done:
        return done[name]
    if name not in cache.images:
        sys.exit('%s: not in the shared cache (try --list)' % name)
    info = cache.image(name)
    out = sdk + info['name']
    done[name] = out
    deps = [mkstub(cache, sdk, r, done) for r in info['reexports'] if r in cache.images]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        # The object is called exit-asm.o on purpose: ld64 refuses to link a
        # dylib that does not itself link libSystem, except (hard-coded
        # grandfathering) when an input file has this name.
        s, o = os.path.join(tmp, 'stub.s'), os.path.join(tmp, 'exit-asm.o')
        with open(s, 'w') as f:
            for want_text, sect in ((True, '__TEXT,__text,regular,pure_instructions'),
                                    (False, '__DATA,__data')):
                f.write('.section %s\n.align 2\n' % sect)
                for sym, text, weak in info['syms']:
                    if text != want_text:
                        continue
                    f.write('.globl "%s"\n' % sym)
                    if weak:
                        f.write('.weak_definition "%s"\n' % sym)
                    f.write('"%s":\n.long 0\n' % sym)
        subprocess.check_call(['clang', '-target', 'armv6-apple-ios4.2', '-c', s, '-o', o])
        cmd = [os.path.join(TC, 'bin', 'arm-apple-darwin10-ld'), '-dylib', '-arch', 'armv6', '-Z',
               '-ios_version_min', '4.2', '-install_name', info['name'],
               '-current_version', ver(info['cur']),
               '-compatibility_version', ver(info['compat']), '-o', out, o]
        for dep in deps:
            cmd += ['-reexport_library', dep]
        subprocess.check_call(cmd)
    # Convenience names the linker searches for: libfoo.dylib, Foo.framework/Foo.
    d, b = os.path.split(out)
    links = []
    if b.startswith('lib') and b.endswith('.dylib') and b.count('.') > 1:
        links.append(os.path.join(d, b.split('.')[0] + '.dylib'))
    if '.framework/Versions/' in out:
        fw = out[:out.index('.framework/') + len('.framework')]
        links.append(os.path.join(fw, b))
    for l in links:
        if not os.path.lexists(l):
            os.symlink(os.path.relpath(out, os.path.dirname(l)), l)
    print('stub %-70s %5d symbols  %s (compat %s)' % (
        info['name'], len(info['syms']), ver(info['cur']), ver(info['compat'])))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--cache', default=os.path.join(TC, 'cache', 'dyld_shared_cache_armv6'))
    ap.add_argument('--sdk', default=os.path.join(TC, 'sdk'))
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--symbols', help='build the stubs from this JSON symbol list, not the cache')
    ap.add_argument('--write-list', metavar='LIST', help='write a symbol list (needs the cache)')
    ap.add_argument('--used', nargs='+', default=[], metavar='BIN',
                    help='with --write-list: keep only symbols these binaries import')
    ap.add_argument('names', nargs='*')
    a = ap.parse_args()
    cache = SymbolList(a.symbols) if a.symbols else Cache(a.cache)
    if a.write_list:
        write_list(cache, a.write_list, a.used, a.names)
        return
    if a.list:
        print('\n'.join(sorted(cache.images)))
        return
    done = {}
    for n in a.names:
        mkstub(cache, a.sdk, n, done)


if __name__ == '__main__':
    main()
EOF
    chmod +x "$TC/bin/ios-mkstub"
}

write_crt() {    # our own crt1: `start` for LC_UNIXTHREAD executables
    mkdir -p "$TC/crt" "$SDK/usr/lib"
    cat > "$TC/crt/start.S" <<'EOF'
/* ios3ds crt1 for armv6 iOS 4: the kernel/dyld enter `start` with
 * sp -> argc, argv[0..], NULL, envp[0..], NULL, apple[0..], NULL.
 * dyld has already filled NXArgc/NXArgv/environ/__progname through the
 * __DATA,__program_vars section (see vars.c). Calls
 * exit(main(argc, argv, envp, apple)). */
	.text
	.globl	start
	.align	2
	.arm
start:
	ldr	r0, [sp]		@ argc
	add	r1, sp, #4		@ argv
	add	r4, r0, #1
	add	r2, r1, r4, lsl #2	@ envp
	bic	sp, sp, #7		@ 8-byte stack alignment
	mov	r3, r2
1:	ldr	r4, [r3], #4		@ skip envp -> apple
	cmp	r4, #0
	bne	1b
	bl	_main
	b	_exit
EOF
    cat > "$TC/crt/vars.c" <<'EOF'
/* Program variables dyld (and through it libSystem) expects in the main
 * executable, published through __DATA,__program_vars like Apple's crt1. */
extern const char _mh_execute_header;
int NXArgc = 0;
const char **NXArgv = 0;
const char **environ = 0;
const char *__progname = 0;
struct ProgramVars {
    const void *mh;
    int *NXArgcPtr;
    const char ***NXArgvPtr;
    const char ***environPtr;
    const char **__prognamePtr;
};
static const struct ProgramVars pvars
    __attribute__((used, section("__DATA,__program_vars"))) = {
    &_mh_execute_header, &NXArgc, &NXArgv, &environ, &__progname
};
EOF
    local f="-target $TRIPLE -mfloat-abi=softfp -Os -fno-stack-protector"
    clang $f -c "$TC/crt/start.S" -o "$TC/crt/start.o"
    clang $f -c "$TC/crt/vars.c" -o "$TC/crt/vars.o"
    "$TC/bin/$TOOLPFX-ld" -r -arch armv6 -o "$SDK/usr/lib/crt1.o" \
        "$TC/crt/start.o" "$TC/crt/vars.o"
    ln -sf crt1.o "$SDK/usr/lib/crt1.3.1.o"     # the name clang's driver asks for
}

stage_sdk() {
    say "stub SDK ($SDK)"
    mkdir -p "$SDK" "$TC/cache"
    write_headers
    write_mkstub
    write_crt
    local cache="$TC/cache/dyld_shared_cache_armv6"
    local hfs="$ROOT/build/tools/hfsplus" img="$ROOT/build/staging/rootfs.hfs"
    local from="${IOS_SDK_FROM:-}"
    if [[ -z "$from" ]]; then
        if [[ -s "$cache" || ( -x "$hfs" && -s "$img" ) ]]; then from=cache; else from=list; fi
    fi
    if [[ "$from" == list ]]; then
        # No IPSW here (CI): stubs from the committed list of the symbols our tools import.
        echo "   stubs from $SYMLIST (no dyld cache; IOS_SDK_FROM=cache to force)"
        "$TC/bin/ios-mkstub" --symbols "$SYMLIST" "${STUBS[@]}"
        return
    fi
    if [[ ! -s "$cache" ]]; then
        [[ -x "$hfs" && -s "$img" ]] || die "need $hfs and $img (run 'make fwprep') to read the dyld shared cache"
        "$hfs" "$img" cat /System/Library/Caches/com.apple.dyld/dyld_shared_cache_armv6 > "$cache.tmp"
        mv "$cache.tmp" "$cache"
    fi
    "$TC/bin/ios-mkstub" "${STUBS[@]}"
}

stage_symbols() {   # regenerate $SYMLIST: full stubs from the cache, build our tools, keep what they import
    say "symbol list ($SYMLIST)"
    IOS_SDK_FROM=cache stage_sdk
    [[ -x "$TC/test/hello" ]] || stage_test
    make -C "$ROOT" -s -B userland
    local bins=("$TC/test/hello" "$TC/test/testbundle.bundle" "$TC/test/libios3dstest.dylib")
    while IFS= read -r f; do bins+=("$f"); done < <(find "$ROOT/build/rootfs-add" -type f | sort)
    "$TC/bin/ios-mkstub" --write-list "$SYMLIST" --used "${bins[@]}" -- "${STUBS[@]}"
}

