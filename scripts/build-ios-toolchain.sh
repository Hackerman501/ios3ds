stage_builtins() {   # compiler-rt builtins for armv6 Mach-O (___udivsi3, ___divdi3, ...)
    local lib="$TC/lib/libclang_rt.builtins-armv6.a"
    [[ -s "$lib" ]] && return
    say "compiler-rt builtins"
    fetch_tar "$CRT_URL" "$CRT_SHA" "$SRC/compiler-rt.tar.xz" "$SRC/compiler-rt"
    local b="$SRC/compiler-rt/lib/builtins" o="$TC/builtins-build" f n
    rm -rf "$o"; mkdir -p "$o"
    local skip=" apple_versioning atomic emutls enable_execute_stack eprintf gcc_personality_v0 clear_cache cpu_model os_version_check trampoline_setup fp_mode aeabi_cdcmpeq_check_nan aeabi_cfcmpeq_check_nan aeabi_div0 aeabi_drsub aeabi_frsub chkstk "
    : > "$o/skipped.log"
    for f in "$b"/*.c "$b"/arm/*.S "$b"/arm/*.c; do
        n="$(basename "${f%.*}")"
        # no AEABI on Darwin; no 128-bit ints, 80/128-bit long double on arm32
        case "$n" in int_util) ;; aeabi_*|crt*|*ti*|*tf*|*xf*|*tc[0-9]|*xc[0-9]) continue ;; esac
        [[ "$skip" == *" $n "* ]] && continue
        # arch-specific .S overrides the generic .c of the same name
        [[ "$f" == *.c && "$f" != */arm/* && -e "$b/arm/$n.S" ]] && continue
        clang -target "$TRIPLE" -mfloat-abi=softfp -isysroot "$SDK" -O2 -fno-builtin \
            -fvisibility=hidden -DVISIBILITY_HIDDEN -fno-stack-protector -I"$b" \
            -c "$f" -o "$o/$n.o" 2>> "$o/skipped.log" || echo "SKIPPED $n" >> "$o/skipped.log"
    done
    rm -f "$lib"
    "$TC/bin/$TOOLPFX-ar" rcs "$lib" "$o"/*.o 2>&1 | grep -v 'has no symbols' || true
    echo "   $(ls "$o"/*.o | wc -l) objects, $(grep -c '^SKIPPED' "$o/skipped.log" || true) skipped (see $o/skipped.log)"
}

