#!/usr/bin/env python3
"""Derive the GL dispatch-slot table for the engine from the user's own
dyld_shared_cache_armv6 (iOS 4.2.1 8C148) and write gl_slots.h.

  genslots.py <dyld_shared_cache_armv6> [-o gl_slots.h]

OpenGLES.framework exports every gl* function as a trampoline:

    mrc p15,0,rT,c13,c0,3        ; TPIDRURO
    ldr rX,[rT,#0x78]            ; per-thread EAGL context block
    ...
    ldr r0,[rX,#0xC]             ; engine GC
    ldr r12,[rX,#0x10+4*slot]    ; __GLIFunctionDispatchRec entry
    bx/blx r12

so the slot of each API function can be read off the code. The slot names
(for the comments, and as a cross-check of the table size) come from the
ObjC @encode of __GLIFunctionDispatchRec in the same image. Only names and
numbers are emitted; no Apple code.
"""
import mmap
import re
import struct
import sys


def main():
    out = "gl_slots.h"
    args = sys.argv[1:]
    if "-o" in args:
        i = args.index("-o")
        out = args[i + 1]
        del args[i:i + 2]
    f = open(args[0], "rb")
    d = mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ)
    mo, mc, io, ic = struct.unpack_from("<IIII", d, 16)
    maps = [struct.unpack_from("<QQQII", d, mo + i * 32) for i in range(mc)]

    def off(a):
        for addr, size, fo, _, _ in maps:
            if addr <= a < addr + size:
                return a - addr + fo
        raise ValueError(hex(a))

    base = None
    for i in range(ic):
        addr, _, _, po, _ = struct.unpack_from("<QQQII", d, io + i * 32)
        if d[po:d.find(b"\0", po)].endswith(b"/OpenGLES.framework/OpenGLES"):
            base = addr
    if base is None:
        sys.exit("OpenGLES not in this cache")
    o = off(base)
    ncmds = struct.unpack_from("<I", d, o + 16)[0]
    p = o + 28
    sym = None
    text_end = 0
    while ncmds:
        cmd, cl = struct.unpack_from("<II", d, p)
        if cmd == 2:
            sym = struct.unpack_from("<IIII", d, p + 8)
        if cmd == 1 and d[p + 8:p + 14] == b"__TEXT":
            va, vs = struct.unpack_from("<II", d, p + 24)
            text_end = va + vs
        p += cl
        ncmds -= 1
    so, ns, stro, _ = sym
    funcs = []
    for i in range(ns):
        strx, t, sect, desc, val = struct.unpack_from("<IBBHI", d, so + i * 12)
        if (t & 0x0E) != 0x0E or not val or val >= text_end:
            continue
        name = d[stro + strx:d.find(b"\0", stro + strx)].decode("latin1")
        funcs.append((val, name))
    funcs.sort()
    i = d.find(b'__GLIFunctionDispatchRec="')
    enc = d[i:d.find(b"\0", i)].decode()
    names = re.findall(r'"([a-zA-Z_0-9]+)"\^\?', enc)
    half = len(names) // 2
    if names[:half] == names[half:]:
        names = names[:half]
    slots = {}
    for k, (va, name) in enumerate(funcs):
        if not re.match(r"_gl[A-Z]", name):
            continue
        end = funcs[k + 1][0] if k + 1 < len(funcs) else va + 0x100
        ctxreg = None
        slot = None
        for a in range(va, min(end, va + 0x100), 4):
            w = struct.unpack_from("<I", d, off(a))[0]
            if (w & 0x0FF00000) != 0x05900000:      # ldr rd,[rn,#+imm]
                continue
            rn, rd, imm = (w >> 16) & 15, (w >> 12) & 15, w & 0xFFF
            if imm == 0x78 and ctxreg is None:
                ctxreg = rd
            elif ctxreg is not None and rn == ctxreg and imm >= 0x10 and imm != 0x78:
                slot = (imm - 0x10) // 4
                break
        if slot is None:
            sys.exit("could not decode trampoline %s" % name)
        slots[name[1:]] = slot
    with open(out, "w") as h:
        h.write("/* Generated by genslots.py from the 8C148 dyld shared cache: GL API\n"
                " * function -> index in OpenGLES.framework's __GLIFunctionDispatchRec\n"
                " * (%d slots). Interface facts only. */\n" % len(names))
        h.write("#ifndef GL_SLOTS_H\n#define GL_SLOTS_H\n#define GLI_NSLOTS %d\n" % len(names))
        for n, s in sorted(slots.items(), key=lambda x: (x[1], x[0])):
            h.write("#define SLOT_%-44s %4d /* %s */\n" % (n, s, names[s] if s < len(names) else "?"))
        h.write("#endif\n")
    print("%d API functions, %d dispatch slots -> %s" % (len(slots), len(names), out))


if __name__ == "__main__":
    main()
